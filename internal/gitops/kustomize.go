package gitops

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// KustomizePatch is one strategic-merge patch file.
type KustomizePatch struct {
	Filename string
	Body     string
}

// Kustomize renders the changes as strategic-merge patches.
//
// This is the path that avoids the problem which stops everyone else. Mapping
// a rendered object back to the Helm values that produced it is genuinely hard;
// a Kustomize patch does not need the mapping at all, because it addresses the
// object by kind, name and namespace, which is exactly what a finding already
// carries. The overlay owner keeps their base untouched.
func Kustomize(changes []Change) ([]KustomizePatch, string) {
	type key struct{ ns, kind, name string }
	byWorkload := map[key][]Change{}
	var order []key
	for _, c := range changes {
		k := key{c.Namespace, c.Kind, c.Name}
		if _, seen := byWorkload[k]; !seen {
			order = append(order, k)
		}
		byWorkload[k] = append(byWorkload[k], c)
	}
	sort.Slice(order, func(i, j int) bool {
		a, b := order[i], order[j]
		if a.ns != b.ns {
			return a.ns < b.ns
		}
		if a.name != b.name {
			return a.name < b.name
		}
		return a.kind < b.kind
	})

	var out []KustomizePatch
	var list bytes.Buffer
	list.WriteString("patches:\n")
	for _, k := range order {
		var b bytes.Buffer
		fmt.Fprintf(&b, "# Generated by tare. The evidence for each number is in the pull request body.\n")
		apiVersion := "apps/v1"
		if k.kind == "ReplicationController" {
			apiVersion = "v1"
		}
		fmt.Fprintf(&b, "apiVersion: %s\nkind: %s\nmetadata:\n  name: %s\n", apiVersion, k.kind, k.name)
		if k.ns != "" {
			fmt.Fprintf(&b, "  namespace: %s\n", k.ns)
		}
		b.WriteString("spec:\n  template:\n    spec:\n      containers:\n")
		for _, c := range byWorkload[k] {
			// Quoted: a container named 123 is otherwise the integer 123, and
			// the patch no longer matches it.
			fmt.Fprintf(&b, "        - name: %q\n          resources:\n", c.Container)
			if c.CPURequest != nil || c.MemRequest != nil {
				b.WriteString("            requests:\n")
				if c.CPURequest != nil {
					fmt.Fprintf(&b, "              cpu: %q\n", CPUQuantity(*c.CPURequest))
				}
				if c.MemRequest != nil {
					fmt.Fprintf(&b, "              memory: %q\n", MemQuantity(*c.MemRequest))
				}
			}
			if c.CPULimit != nil || c.MemLimit != nil {
				b.WriteString("            limits:\n")
				if c.CPULimit != nil {
					fmt.Fprintf(&b, "              cpu: %q\n", CPUQuantity(*c.CPULimit))
				}
				if c.MemLimit != nil {
					fmt.Fprintf(&b, "              memory: %q\n", MemQuantity(*c.MemLimit))
				}
			}
		}
		// The kind is in the name: Deployment/web and StatefulSet/web are
		// different objects, and without it the second overwrote the first.
		name := fmt.Sprintf("tare-%s-%s-%s.yaml", k.ns, strings.ToLower(k.kind), k.name)
		out = append(out, KustomizePatch{Filename: name, Body: b.String()})
		fmt.Fprintf(&list, "  - path: %s\n", name)
	}
	return out, list.String()
}
