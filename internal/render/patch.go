func Cores(m int64) string {
	if m >= 1000 {
		return fmt.Sprintf("%.1f cores", float64(m)/1000)
	}
	return fmt.Sprintf("%dm", m)
}

// printPatches emits runnable `kubectl patch` commands, one per workload.
//
// It deliberately does not emit a partial manifest for `kubectl apply`: apply
// performs a three-way merge and treats the document as the complete desired
// state, so a fragment containing only resources nulls out the selector and the
// image and is rejected. `kubectl patch --type=strategic` touches only the
// fields named, which is what a right-sizer should ever do.
func (p *printer) printPatches(fs []analyze.Finding) {
	// gitops.Plan is the one place that decides what tare will write, so the
	// script and diff --write cannot drift apart: they already did once, over
	// IDLE, and the script also wrote "0" for every field it had no number for.
	changes, skipped := gitops.Plan(fs)

	type wl struct{ ns, kind, name string }
	byWorkload := map[wl][]gitops.Change{}
	var order []wl
	for _, c := range changes {
		if c.CPURequest == nil && c.CPULimit == nil && c.MemRequest == nil && c.MemLimit == nil {
			continue // nothing to apply, and a partial patch is worse than none
		}
		k := wl{c.Namespace, c.Kind, c.Name}
		if _, seen := byWorkload[k]; !seen {
			order = append(order, k)
		}
		byWorkload[k] = append(byWorkload[k], c)
	}

	// The script's comments carry reason codes, which a Change does not.
	type ctr struct{ ns, workload, container string }
	reasons := map[ctr][]analyze.Reason{}
	for _, f := range fs {
		reasons[ctr{f.Namespace, f.Workload, f.Container}] = f.Reasons
	}

	for _, s := range skipped {
		fmt.Fprintf(p.diag, "skipped %s [%s]: %s\n", s.Workload, s.Container, s.Why)
	}

	if len(order) == 0 {
		fmt.Fprintln(p.diag, "no applicable recommendations: nothing to patch")
		return
	}

	fmt.Fprintln(p.out, "#!/bin/sh")
	fmt.Fprintln(p.out, "# Generated by tare. Review before running; add --dry-run=server to check first.")
	for _, s := range skipped {
		fmt.Fprintf(p.out, "# skipped %s [%s]: %s\n", s.Workload, s.Container, s.Why)
	}

	for _, k := range order {
		fmt.Fprintf(p.out, "\n# %s/%s/%s\n", k.ns, k.kind, k.name)
		var containers []map[string]any
		for _, c := range byWorkload[k] {
			for _, r := range reasons[ctr{c.Namespace, c.Kind + "/" + c.Name, c.Container}] {
				fmt.Fprintf(p.out, "#   %s %s\n", r.Code, wrapComment(r.Text))
			}
			// A strategic merge patch touches only the fields it names, so a
			// value tare has no number for is left out rather than written as
			// zero, which would strip it.
			req, lim := map[string]string{}, map[string]string{}
			if c.CPURequest != nil {
				req["cpu"] = gitops.CPUQuantity(*c.CPURequest)
			}
			if c.MemRequest != nil {
				req["memory"] = gitops.MemQuantity(*c.MemRequest)
			}
			if c.CPULimit != nil {
				lim["cpu"] = gitops.CPUQuantity(*c.CPULimit)
			}
			if c.MemLimit != nil {
				lim["memory"] = gitops.MemQuantity(*c.MemLimit)
			}
			res := map[string]any{}
			if len(req) > 0 {
				res["requests"] = req
			}
			if len(lim) > 0 {
				res["limits"] = lim
			}
			containers = append(containers, map[string]any{
				"name": c.Container, "resources": res,
			})
		}
		patch := map[string]any{
			"spec": map[string]any{
				"template": map[string]any{
					"spec": map[string]any{"containers": containers},
				},
			},
		}
		b, _ := json.Marshal(patch) // maps of strings cannot fail to encode
		fmt.Fprintf(p.out, "kubectl -n %s patch %s %s --type=strategic -p %s\n",
			k.ns, strings.ToLower(k.kind), k.name, shellQuote(string(b)))
	}
}

// shellQuote makes a JSON document safe as a single shell argument.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func wrapComment(s string) string {
	return strings.ReplaceAll(s, "\n", " ")
}
