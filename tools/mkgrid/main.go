// Command mkgrid generates internal/report/grid_ember.go, the table behind
// --grid-intensity <country>, from Ember's Yearly Electricity Data.
//
//	curl -o yearly.csv https://storage.googleapis.com/emb-prod-bkt-publicdata/public-downloads/yearly_full_release_long_format.csv
//	go run ./tools/mkgrid yearly.csv > internal/report/grid_ember.go
//
// Each country gets its most recent year, and the year is kept beside the
// value: an old figure printed as if current is a clean wrong number.
package main

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"go/format"
	"io"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

// maxAge is how many years behind the newest figure an entry may be.
const maxAge = 3

type entry struct {
	area, iso3 string
	year       int
	value      float64
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: mkgrid yearly_full_release_long_format.csv")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "mkgrid:", err)
		os.Exit(1)
	}
}

func run(path string, out io.Writer) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	r := csv.NewReader(f)
	header, err := r.Read()
	if err != nil {
		return err
	}
	col := map[string]int{}
	for i, h := range header {
		col[h] = i
	}
	for _, need := range []string{"Area", "ISO 3 code", "Year", "Area type", "Variable", "Unit", "Value"} {
		if _, ok := col[need]; !ok {
			return fmt.Errorf("column %q missing: the Ember format changed", need)
		}
	}

	latest := map[string]entry{}
	for {
		rec, err := r.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		if rec[col["Variable"]] != "CO2 intensity" || rec[col["Area type"]] != "Country or economy" || rec[col["Value"]] == "" {
			continue
		}
		if u := rec[col["Unit"]]; u != "gCO2/kWh" {
			return fmt.Errorf("unexpected unit %q for %s", u, rec[col["Area"]])
		}
		year, err := strconv.Atoi(rec[col["Year"]])
		if err != nil {
			return err
		}
		v, err := strconv.ParseFloat(rec[col["Value"]], 64)
		if err != nil {
			return err
		}
		iso := rec[col["ISO 3 code"]]
		// A zero intensity is a gap in Ember's data, not a clean grid, and
		// would print 0 kgCO2e for a country that emits.
		if iso == "" || v <= 0 {
			continue
		}
		area := strings.TrimSuffix(rec[col["Area"]], " (the)")
		if e, ok := latest[iso]; !ok || year > e.year {
			latest[iso] = entry{area, iso, year, v}
		}
	}
	if len(latest) < 100 {
		return fmt.Errorf("only %d countries found: the Ember format changed", len(latest))
	}

	newest := 0
	for _, e := range latest {
		newest = max(newest, e.year)
	}
	// A country whose last figure is years old is left out rather than
	// printed beside current ones.
	var es []entry
	for _, e := range latest {
		if e.year >= newest-maxAge {
			es = append(es, e)
		}
	}
	sort.Slice(es, func(a, b int) bool { return es[a].area < es[b].area })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/mkgrid on %s from Ember Yearly Electricity Data; DO NOT EDIT.\n", time.Now().UTC().Format("2006-01-02"))
	fmt.Fprintln(&b, "// Source: https://ember-energy.org/data/yearly-electricity-data/ (CC-BY-4.0).")
	fmt.Fprintln(&b, "\npackage report\n\nvar emberGrid = []GridEntry{")
	for _, e := range es {
		fmt.Fprintf(&b, "\t{%q, %q, %d, %s},\n", e.area, strings.ToUpper(e.iso3), e.year, strconv.FormatFloat(e.value, 'f', -1, 64))
	}
	fmt.Fprintln(&b, "}")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	_, err = out.Write(src)
	return err
}
